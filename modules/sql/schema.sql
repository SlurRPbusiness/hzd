CREATE TABLE IF NOT EXISTS `hzd_users` (
    `identifier` VARCHAR(64) NOT NULL,
    `name` VARCHAR(64) NOT NULL,
    `kills` INT UNSIGNED NOT NULL DEFAULT 0,
    `deaths` INT UNSIGNED NOT NULL DEFAULT 0,
    `headshots` INT UNSIGNED NOT NULL DEFAULT 0,
    `matches_played` INT UNSIGNED NOT NULL DEFAULT 0,
    `matches_won` INT UNSIGNED NOT NULL DEFAULT 0,
    `elo` INT UNSIGNED NOT NULL DEFAULT 1000,
    `coins` INT UNSIGNED NOT NULL DEFAULT 0,
    `xp` INT UNSIGNED NOT NULL DEFAULT 0,
    `level` INT UNSIGNED NOT NULL DEFAULT 1,
    `settings` LONGTEXT NULL,
    `skin` LONGTEXT NULL,
    `created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `last_seen` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`identifier`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
